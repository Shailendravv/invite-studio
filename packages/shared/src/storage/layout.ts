// Folder layout inside storage (see plan section 3):
//   staging/<orderId>/                      while an order is being processed
//   clients/<client-slug>/<YYYY-MM-DD>_<event-type>_<orderId>/   once done

export const FILES = {
  raw: "raw.txt",
  spec: "spec.json",
  uploads: "uploads",
  video: "invitation.mp4",
  share: "invitation_share.mp4",
  thumb: "thumbnail.png",
  log: "render.log",
  qa: "qa",
} as const;

export function stagingFolder(orderId: string): string {
  return `staging/${orderId}`;
}

export function clientFolder(args: { clientSlug: string; date: string; eventType: string; orderId: string }): string {
  const date = /^\d{4}-\d{2}-\d{2}$/.test(args.date) ? args.date : new Date().toISOString().slice(0, 10);
  return `clients/${args.clientSlug}/${date}_${args.eventType}_${args.orderId}`;
}

export function fileKey(folder: string, file: string): string {
  return `${folder.replace(/\/+$/, "")}/${file}`;
}

/** Upload file names are generated by us; this keeps the extension only. */
export function uploadKey(folder: string, fileName: string): string {
  return `${folder}/${FILES.uploads}/${fileName}`;
}
